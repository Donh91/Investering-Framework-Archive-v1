let language = 'da';
const original = new WeakMap();
const attributes = new WeakMap();
const skip = new Set(['SCRIPT','STYLE','NOSCRIPT','SVG','CODE','PRE']);

export function currentLanguage() { return language; }

export function initializeLanguage() {
  try {
    const stored = window.localStorage.getItem('cn-vnext-lang');
    if (stored === 'en' || stored === 'da') language = stored;
  } catch (_) { /* non-essential preference */ }
  document.documentElement.lang = language;
}

function translateNode(node) {
  if (!original.has(node)) original.set(node,node.nodeValue);
  const baseline = original.get(node);
  const content = baseline.trim();
  if (!content) return;
  const translated = language === 'en' ? (translations[content] || content) : content;
  node.nodeValue = baseline.slice(0,baseline.indexOf(content)) + translated + baseline.slice(baseline.indexOf(content)+content.length);
}

export function translateInterface() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement && !skip.has(node.parentElement.tagName)) nodes.push(node);
  }
  for (const node of nodes) translateNode(node);
  for (const element of document.querySelectorAll('[aria-label],[title]')) {
    if (!attributes.has(element)) attributes.set(element,{
      label:element.getAttribute('aria-label'), title:element.getAttribute('title')
    });
    const base = attributes.get(element);
    for (const [attr,key] of [['aria-label','label'],['title','title']]) {
      if (base[key]) element.setAttribute(attr,language === 'en' ? (translations[base[key]] || base[key]) : base[key]);
    }
  }
  document.documentElement.lang = language;
  for (const button of document.querySelectorAll('[data-lang]')) {
    const selected = button.dataset.lang === language;
    button.classList.toggle('is-selected',selected);
    button.setAttribute('aria-pressed',String(selected));
  }
}

export function selectLanguage(next, onChange) {
  if (!['da','en'].includes(next)) return;
  language = next;
  try { window.localStorage.setItem('cn-vnext-lang',next); } catch (_) {}
  if (typeof onChange === 'function') onChange();
  translateInterface();
}
